#!/usr/bin/env python3
"""Bring Game Studio's "Worlds Lobby" scene into Möbius Worlds.

  python3 tools/bundle_lobby.py [<game-studio-app-id>] [<game-id>]

Reads the scene game (games/<id>.html in Game Studio's storage), copies every
3D model it places into lobby/models/ (shipped as the app's packaged assets,
served at /app-assets/by-id/<app>/models/<name>.glb), and writes lobby_game.js
with the game file and the model list. Worlds adds your ghost, the other
players and the session bridge at run time (ui/LobbyWorld.jsx), so the scene
itself stays exactly as it was made in the studio.

Also refreshes the studio's game helper (kart_runtime.js), which both the lobby
and Möbius Kart run with. Re-run after changing the lobby in Game Studio, then
apply the app (or publish the game from the studio, which does both).
"""
import json
import re
import shutil
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
DATA = Path('/data')
MANIFEST = APP / 'mobius.json'

studio_id = sys.argv[1] if len(sys.argv) > 1 else '12'
game_id = sys.argv[2] if len(sys.argv) > 2 else 'g-qovj6o'
studio = DATA / 'apps' / studio_id
html = (studio / 'games' / f'{game_id}.html').read_text(encoding='utf-8')
match = re.search(r'<script type="application/json" id="scene">(.*?)</script>', html, re.S)
if not match:
  sys.exit('That game is not a 3D scene, so it cannot be the Worlds lobby.')
scene = json.loads(match.group(1))
assets = sorted({o['asset'] for o in scene.get('objects', []) if o.get('type') == 'model' and o.get('asset')})

out = APP / 'lobby' / 'models'
if out.exists():
  shutil.rmtree(out)
out.mkdir(parents=True)
sizes, missing = {}, []
for name in assets:
  src = studio / 'models' / f'{name}.glb'
  if not src.exists():
    missing.append(name)
    continue
  shutil.copyfile(src, out / f'{name}.glb')
  sizes[name] = src.stat().st_size

(APP / 'lobby_game.js').write_text(
  '// Generated by tools/bundle_lobby.py from Game Studio. Edit the lobby there, then re-run the tool.\n'
  f'export const LOBBY = {json.dumps({"id": game_id, "name": scene.get("name"), "models": sizes}, ensure_ascii=False)}\n'
  f'export const LOBBY_HTML = {json.dumps(html, ensure_ascii=False)}\n', encoding='utf-8')
runtime = (DATA / 'apps' / 'game-studio' / 'gameRuntime.js').read_text(encoding='utf-8')
(APP / 'kart_runtime.js').write_text(
  '// Copied from Game Studio\'s gameRuntime.js (the studio helper games run with) by tools/bundle_lobby.py and bundle_kart.py.\n'
  + runtime, encoding='utf-8')

# Keep the manifest's packaged-asset list exactly in step with the models (surgical edit).
text = MANIFEST.read_text(encoding='utf-8')
block = '"static_assets": {\n' + ',\n'.join(
  f'    "models/{n}.glb": "lobby/models/{n}.glb"' for n in sizes) + '\n  }'
text, count = re.subn(r'"static_assets": \{.*?\n  \}', lambda _: block, text, flags=re.S)
if count != 1:
  sys.exit('mobius.json has no "static_assets" block to update.')
MANIFEST.write_text(text, encoding='utf-8')

print(json.dumps({'ok': True, 'models': len(sizes), 'bytes': sum(sizes.values()), 'missing': missing}))
