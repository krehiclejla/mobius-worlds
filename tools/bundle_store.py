#!/usr/bin/env python3
"""Stock the lobby's App Store stand with apps from the Möbius App Store.

  python3 tools/bundle_store.py [path/to/catalog.json]

Reads the App Store's catalog (default: the installed Store app's catalog.json),
keeps the apps made for everyone (audience "general"), fetches each one's icon
from its repository, shrinks it, and writes store_featured.js: name, tagline,
category, repository and a small inline icon per app. Worlds shows them on the
stand's card and floating above the stand, so the lobby needs no network to
show them. Re-run when the Store's catalog changes, then apply the app.
"""
import base64
import io
import json
import sys
import urllib.request
from pathlib import Path

from PIL import Image

APP = Path(__file__).resolve().parent.parent
catalog_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/data/apps/store/catalog.json')
catalog = json.loads(catalog_path.read_text(encoding='utf-8'))

# The Store's own shelves, in the order the stand shows them.
SHELVES = ['play', 'create', 'explore', 'everyday', 'productivity']
LABELS = {'play': 'Play', 'create': 'Create', 'explore': 'Explore', 'everyday': 'Everyday', 'productivity': 'Productivity'}


def fetch(url):
  with urllib.request.urlopen(url, timeout=20) as response:
    return response.read()


def icon_data(item):
  manifest = json.loads(fetch(item['manifest_url']))
  raw = fetch(item['raw_base'] + (manifest.get('icon') or 'icon.png'))
  image = Image.open(io.BytesIO(raw)).convert('RGBA')
  image.thumbnail((96, 96), Image.LANCZOS)
  out = io.BytesIO()
  image.save(out, 'WEBP', quality=82, method=6)
  return 'data:image/webp;base64,' + base64.b64encode(out.getvalue()).decode()


apps, failed = [], []
general = [a for a in catalog['apps'] if a.get('audience') == 'general' and a.get('collection') in SHELVES]
general.sort(key=lambda a: (not a.get('listing', {}).get('featured'),
                            SHELVES.index(a.get('collection')) if a.get('collection') in SHELVES else len(SHELVES)))
for item in general:
  try:
    icon = icon_data(item)
  except Exception as err:  # an app without a reachable icon is left off the stand
    failed.append(f"{item['id']}: {err}")
    continue
  apps.append({
    'id': item['id'],
    'name': item['name'],
    'tagline': item.get('listing', {}).get('tagline') or item.get('summary') or item.get('description', ''),
    'shelf': LABELS.get(item.get('collection'), 'Apps'),
    'repo': item.get('repo', ''),
    'featured': bool(item.get('listing', {}).get('featured')),
    'icon': icon,
  })

(APP / 'store_featured.js').write_text(
  '// Generated by tools/bundle_store.py from the Möbius App Store catalog. Re-run it to refresh.\n'
  f'export const STORE_UPDATED = {json.dumps(catalog.get("updated", ""))}\n'
  f'export const STORE_APPS = {json.dumps(apps, ensure_ascii=False, indent=1)}\n', encoding='utf-8')
print(json.dumps({'ok': True, 'apps': len(apps), 'failed': failed,
                  'bytes': (APP / 'store_featured.js').stat().st_size}))
