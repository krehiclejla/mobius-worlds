#!/usr/bin/env python3
"""Copy Ghost Drop from Game Studio into Worlds.

  python3 tools/bundle_ghostdrop.py [<game-studio-app-id>] [<game-id>]

Reads the game (games/<id>.html in Game Studio's storage) and writes:
  - ghostdrop_game.js: the game page for the Worlds frame, and
  - ghostdrop_config.json: the game's one config block, read by ghostdrop.py.
The config block (<script type="application/json" id="ghostdrop-config">) is the
single place to change layer count, tile delay, fall speed and minimum players.
Run it again after the game changes in Game Studio.
"""
import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
DATA = Path('/data')

studio_id = sys.argv[1] if len(sys.argv) > 1 else '12'
game_id = sys.argv[2] if len(sys.argv) > 2 else 'g-be99773c'
html = (DATA / 'apps' / studio_id / 'games' / f'{game_id}.html').read_text(encoding='utf-8')

block = re.search(r'<script type="application/json" id="ghostdrop-config">\s*(.*?)\s*</script>', html, re.S)
if not block:
  sys.exit('ghostdrop-config block not found in the game')
config = json.loads(block.group(1))
if '<script type="module">' not in html:
  sys.exit('the game needs its module script for the Worlds frame to hand it the ghosts')

(APP / 'ghostdrop_config.json').write_text(json.dumps(config, indent=2) + '\n', encoding='utf-8')
(APP / 'ghostdrop_game.js').write_text(
  '// Generated by tools/bundle_ghostdrop.py from Game Studio. Edit the game there, then re-run the tool.\n'
  f'export const GHOSTDROP_HTML = {json.dumps(html, ensure_ascii=False)}\n', encoding='utf-8')
print(json.dumps({'ok': True, 'game_bytes': len(html), 'layers': config['layers']}))
