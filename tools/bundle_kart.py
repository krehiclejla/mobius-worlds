#!/usr/bin/env python3
"""Copy Möbius Kart from Game Studio into Worlds.

  python3 tools/bundle_kart.py [<game-studio-app-id>] [<game-id>]

Reads the game (games/<id>.html in Game Studio's storage) and Game Studio's
game runtime, and writes kart_game.js and kart_runtime.js next to this app.
The ghost models and logo are not copied: Worlds hands the game its own
(models_ghosts.js and the LOGO in models.js) when a race starts. Run it again
after the game changes in Game Studio.
"""
import json
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
DATA = Path('/data')

studio_id = sys.argv[1] if len(sys.argv) > 1 else '12'
game_id = sys.argv[2] if len(sys.argv) > 2 else 'mobius-kart'
html = (DATA / 'apps' / studio_id / 'games' / f'{game_id}.html').read_text(encoding='utf-8')
runtime = (DATA / 'apps' / 'game-studio' / 'gameRuntime.js').read_text(encoding='utf-8')

(APP / 'kart_game.js').write_text(
  '// Generated by tools/bundle_kart.py from Game Studio. Edit the game there, then re-run the tool.\n'
  f'export const KART_HTML = {json.dumps(html, ensure_ascii=False)}\n', encoding='utf-8')
(APP / 'kart_runtime.js').write_text(
  '// Copied from Game Studio\'s gameRuntime.js (the studio helper games run with) by tools/bundle_lobby.py and bundle_kart.py.\n'
  + runtime, encoding='utf-8')
print(json.dumps({'ok': True, 'game_bytes': len(html), 'runtime_bytes': len(runtime)}))
